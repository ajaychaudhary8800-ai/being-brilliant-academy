#!/bin/sh
# Verify historical and current V5 backup contents without trusting the path
# embedded in SHA256SUMS. Earlier backups encode absolute /backups/... paths;
# copied offsite checkpoints may reside in a different isolated directory.
# This validates integrity, NOT signature/authenticity or point-in-time coherence.
set -eu

backup_dir="${1:?Usage: verify-checksums.sh BACKUP_DIR}"
manifest="$backup_dir/SHA256SUMS"

fail() {
  echo "V5_BACKUP_CHECKSUM_VERIFICATION=FAIL" >&2
  exit 1
}

[ -f "$manifest" ] && [ -f "$backup_dir/database.dump" ] && \
  [ -f "$backup_dir/files.tar.gz" ] || fail

expected_db=''
expected_files=''
count=0

while IFS= read -r line || [ -n "$line" ]; do
  hash=${line%% *}
  suffix=${line#"$hash"}

  [ "${#hash}" -eq 64 ] || fail
  case "$hash" in
    *[!0123456789abcdef]*|'') fail ;;
  esac

  # SHA256SUMS generated by sha256sum uses two literal spaces before a path.
  # Never execute, expand or open that potentially untrusted archived path.
  case "$suffix" in
    '  '*) saved_path=${suffix#'  '} ;;
    *) fail ;;
  esac

  case "$saved_path" in
    database.dump|*/database.dump)
      [ -z "$expected_db" ] || fail
      expected_db="$hash"
      ;;
    files.tar.gz|*/files.tar.gz)
      [ -z "$expected_files" ] || fail
      expected_files="$hash"
      ;;
    *) fail ;;
  esac

  count=$((count + 1))
done < "$manifest"

[ "$count" -eq 2 ] && [ -n "$expected_db" ] && \
  [ -n "$expected_files" ] || fail

actual_db="$(sha256sum "$backup_dir/database.dump" 2>/dev/null)" || fail
actual_db=${actual_db%% *}
actual_files="$(sha256sum "$backup_dir/files.tar.gz" 2>/dev/null)" || fail
actual_files=${actual_files%% *}

[ "$actual_db" = "$expected_db" ] && \
  [ "$actual_files" = "$expected_files" ] || fail

echo "V5_BACKUP_CHECKSUM_VERIFICATION=PASS"
